def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    subcommands = parser.add_subparsers(dest="command", required=True)
    stage = subcommands.add_parser("stage")
    stage.add_argument("--trial-id", required=True)
    stage.add_argument("--blender", default="blender")
    commands = subcommands.add_parser("commands")
    commands.add_argument("--trial-id", required=True)
    capture = subcommands.add_parser("capture-authority")
    capture.add_argument("--trial-id", required=True)
    validate = subcommands.add_parser("validate")
    validate.add_argument("--trial-id", required=True)
    validate.add_argument("--run-id")
    return parser


def main() -> None:
    args = _parser().parse_args()
    if args.command == "stage":
        print(stage_trial(trial_id=args.trial_id, blender=args.blender))
    elif args.command == "commands":
        print("\n".join(" ".join(command) for command in compiled_commands(trial_id=args.trial_id)))
    elif args.command == "capture-authority":
        print(capture_authority(trial_id=args.trial_id))
    else:
        print(
            validate_trial(
                trial_id=args.trial_id,
                run_id=args.run_id,
            )
        )


if __name__ == "__main__":
    main()
