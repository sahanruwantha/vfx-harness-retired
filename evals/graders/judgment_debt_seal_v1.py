def _json(path: Path, where: str) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"{where} is not readable JSON: {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise ValueError(f"{where} must be a JSON object: {path}")
    return value


def _exact(value: object, fields: set[str] | frozenset[str], where: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping) or set(value) != fields:
        found = set(value) if isinstance(value, Mapping) else set()
        raise ValueError(
            f"{where} fields mismatch; missing={sorted(fields - found)}; "
            f"unexpected={sorted(found - fields)}"
        )
    return value


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _safe_relative(value: object, where: str) -> str:
    if not isinstance(value, str) or not value or value != value.strip():
        raise ValueError(f"{where} must be a non-empty trimmed relative path")
    path = PurePosixPath(value)
    if path.is_absolute() or any(part in {"", ".", ".."} for part in path.parts):
        raise ValueError(f"{where} must be a normalized relative path")
    return path.as_posix()


def _safe_member(root: Path, locator: object, where: str) -> Path:
    relative = _safe_relative(locator, where)
    candidate = root / relative
    if candidate.is_symlink():
        raise ValueError(f"{where} must not be a symlink: {relative}")
    resolved = candidate.resolve()
    try:
        resolved.relative_to(root.resolve())
    except ValueError as exc:
        raise ValueError(f"{where} escapes its owning root: {relative}") from exc
    return resolved


def _record_digest(record: Mapping[str, Any], digest_field: str, where: str) -> dict[str, Any]:
    identity = {key: value for key, value in record.items() if key != digest_field}
    if record.get(digest_field) != canonical_digest(identity):
        raise ValueError(f"{where}.{digest_field} does not match its canonical payload")
    return identity


def _atomic_json(path: Path, value: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f"{path.name}.tmp.{os.getpid()}")
    temporary.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(temporary, path)


